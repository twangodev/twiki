import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createCLI } from "../cli/commands";
import {
  projectJSONSchema,
  siteDefaults,
} from "../site/tooling/lib/project-schema";

const root = path.resolve(import.meta.dirname, "..");
const outputs = new Map<string, string>();
const page = (title: string, text: string) =>
  `---\ntitle: ${title}\n---\n\n# ${title}\n\n<!-- Generated by bun run docs:generate. Edit the source definitions, not this page. -->\n\n${text}\n`;
const cell = (value: unknown) =>
  String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");
const program = createCLI();
let cli = `Generated from [the actual command definitions](https://github.com/twangodev/twiki/blob/main/cli/commands.ts). This reference follows the checked-out engine source.\n\n`;
cli +=
  "Run `twiki --help` or `twiki <command> --help` for terminal help. Use `--project <directory>` and `--config <file>` to select a vault.\n\n";
for (const command of program.commands) {
  cli += `## ${command.name()}\n\n${command.description()}\n\n\`\`\`text\n${command.helpInformation().trimEnd()}\n\`\`\`\n\n`;
}
cli +=
  "See [[getting-started/index|Getting started]] and [[reference/configuration|Configuration reference]].";
outputs.set("documentation/notes/reference/cli.md", page("CLI reference", cli));
const schema = projectJSONSchema();
outputs.set("cli/twiki.schema.json", JSON.stringify(schema, null, 2) + "\n");
outputs.set(
  "site/src/lib/site-config.json",
  JSON.stringify(siteDefaults, null, 2) + "\n",
);
interface Field {
  type?: string;
  enum?: string[];
  const?: unknown;
  description?: string;
  default?: unknown;
  properties?: Record<string, Field>;
  required?: string[];
}
let config =
  'Generated from [the runtime schema](https://github.com/twangodev/twiki/blob/main/site/tooling/lib/project-schema.ts). The same schema validates configuration and provides TypeScript types.\n\nFor editor completion, add `"$schema": "./node_modules/@twango/twiki/cli/twiki.schema.json"` to a root-level `twiki.config.json`. Adjust the path if your config lives elsewhere. The package also exports `@twango/twiki/schema`.\n\n';
config +=
  "| Field | Type / values | Required | Default | Description |\n| --- | --- | --- | --- | --- |\n";
function fields(object: Field, prefix = "") {
  for (const [name, property] of Object.entries(object.properties ?? {})) {
    const key = prefix + name;
    const type = property.enum
      ? property.enum.map((v) => `\`${v}\``).join(", ")
      : property.const !== undefined
        ? `\`${JSON.stringify(property.const)}\``
        : property.type;
    config += `| \`${key}\` | ${cell(type)} | ${object.required?.includes(name) ? "Yes, when parent exists" : "No"} | ${property.default === undefined ? "—" : cell("`" + JSON.stringify(property.default) + "`")} | ${cell(property.description)} |\n`;
    if (property.properties) fields(property, key + ".");
  }
}
fields(schema as Field);
config +=
  "\nAbsent values preserve context-sensitive defaults: an explicit CLI vault uses filesystem discovery, the vault root as content directory, and private publication. Legacy engine workspaces use Git discovery, `content/` and publication policies. Schema defaults for site metadata match runtime branding defaults.\n\nThe `cloudflare` object passes resource settings to Wrangler; Twiki controls generated `main` and `assets`. Never store an API token here. See [[guides/cloudflare|Cloudflare deployment]], [[guides/authentication|Authentication]] and [[examples/public-vault|Public vault example]].";
outputs.set(
  "documentation/notes/reference/configuration.md",
  page("Configuration reference", config),
);
const changelog = existsSync(path.join(root, "CHANGELOG.md"))
  ? readFileSync(path.join(root, "CHANGELOG.md"), "utf8").replace(
      /^# Changelog\s*/,
      "",
    )
  : `Release Please maintains the changelog as reviewed release PRs merge. See the linked releases for published versions.\n`;
outputs.set(
  "documentation/notes/reference/releases.md",
  page(
    "Release history",
    `${changelog}\n[All GitHub releases](https://github.com/twangodev/twiki/releases) · [npm versions](https://www.npmjs.com/package/@twango/twiki?activeTab=versions)\n\n[[reference/index|Reference]]`,
  ),
);
const check = process.argv.includes("--check");
let stale = false;
for (const [relative, content] of outputs) {
  const file = path.join(root, relative);
  // Release notes change in Release Please PRs; render them as build output rather than requiring a second generated-docs commit.
  if (relative === "documentation/notes/reference/releases.md") {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
    continue;
  }
  if (existsSync(file) && readFileSync(file, "utf8") === content) continue;
  if (check) {
    console.error(`Stale generated documentation: ${relative}`);
    stale = true;
  } else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
if (stale) {
  console.error("Run bun run docs:generate and commit the updated files.");
  process.exitCode = 1;
} else
  console.log(
    check
      ? "Generated documentation is current."
      : "Documentation and editor schema generated.",
  );
